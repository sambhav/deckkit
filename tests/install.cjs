const assert = require('node:assert/strict');
module.exports = async function verifyInstall(page, base) {
  const block = ['::: install', '```sh macos', 'brew install talkdown', '```', '```sh linux', 'curl -fsSL https://example.com | sh', '```', '```powershell windows', 'winget install talkdown', '```', ':::'].join('\n');
  const source = ['id: one', '---', '## One', block, '---', '## Two', block, '---', '## Bad', '::: install', '```sh', 'no system', '```', ':::'].join('\n');
  await page.route('**/install-fixture.html*', route => route.fulfill({ contentType: 'text/html; charset=utf-8', body: '<!doctype html><html data-fonts="off" data-highlight="off" data-icons="off"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><link rel="stylesheet" href="deck.css"><script src="deck.js"></script></head><body><script type="text/markdown">' + source + '</script></body></html>' }));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base + '/install-fixture.html?view=present');
  await page.evaluate(() => localStorage.removeItem('talkdown:choice:os'));
  await page.reload();
  await page.waitForFunction(() => window.Deck?.slides.length === 3);
  const selected = () => page.evaluate(() => [...document.querySelectorAll('.w-install')].map(w => w.querySelector('[role=tab][aria-selected=true]').textContent));
  const detected = await page.evaluate(() => { const ua = navigator.platform + navigator.userAgent; return /iphone|ipad|mac/i.test(ua) ? 'macOS' : /win/i.test(ua) ? 'Windows' : 'Linux'; });
  assert.deepEqual(await selected(), [detected, detected], "the viewer's own system is selected first");
  assert.ok(await page.locator('.slide.active .w-os-pane.on .w-copy').count(), 'each block has a Copy button');
  await page.locator('.slide.active .w-os [role=tab]', { hasText: 'Windows' }).click();
  assert.deepEqual(await selected(), ['Windows', 'Windows'], 'a pick switches every install block');
  assert.equal(await page.locator('.slide.active .w-os-pane.on pre').textContent(), 'winget install talkdown');
  assert.deepEqual(await page.evaluate(() => Deck.store.get('choice:os')), ['windows']);
  await page.locator('.slide.active .w-os [role=tab][aria-selected=true]').focus();
  await page.keyboard.press('ArrowLeft');
  assert.deepEqual(await selected(), ['Linux', 'Linux'], 'arrow keys move between systems');
  assert.equal(await page.evaluate(() => Deck.cur), 0, 'arrow keys stay on the tabs');
  await page.keyboard.press('Home');
  assert.deepEqual(await selected(), ['macOS', 'macOS']);
  await page.evaluate(() => { localStorage.setItem('talkdown:choice:os', JSON.stringify(['linux'])); dispatchEvent(new StorageEvent('storage', { key: 'talkdown:choice:os' })); });
  assert.deepEqual(await selected(), ['Linux', 'Linux'], 'a pick in another window is followed');
  await page.evaluate(() => Deck.setView('read'));
  assert.equal(await page.locator('.w-install >> nth=0').locator('.w-os-pane:visible').count(), 1, 'the article shows one system with the switcher');
  assert.equal(await page.locator('.w-install >> nth=0').locator('.w-os').isVisible(), true);
  assert.equal(await page.locator('.td-error').count(), 1, 'a fence without a system fails visibly');
  assert.match(await page.locator('.td-error').textContent(), /install needs a system/);
  await page.reload();
  await page.waitForFunction(() => window.Deck?.slides.length === 3);
  assert.deepEqual(await selected(), ['Linux', 'Linux'], 'the pick is remembered on the next visit');
  await page.evaluate(() => localStorage.removeItem('talkdown:choice:os'));
};
