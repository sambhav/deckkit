const assert = require('node:assert/strict');
module.exports = async function verifyQuiz(page, base) {
  const source = '## Check\n::: quiz\n### What does p99 measure?\n- [ ] Average latency\n- [x] Latency 99% of requests beat\n- [ ] Peak latency\n\nThe tail matters.\n:::\n---\n## Invalid\n::: quiz\nKeep this prose.\n:::';
  await page.route('**/quiz-fixture.html*', route => route.fulfill({ contentType: 'text/html', body:
    '<!doctype html><html data-fonts="off" data-highlight="off" data-icons="off"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><link rel="stylesheet" href="deck.css"><script src="deck.js"></script></head><body><script type="text/markdown">' + source + '</script></body></html>' }));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base + '/quiz-fixture.html?view=present');
  await page.waitForFunction(() => window.Deck?.slides.length === 2);
  const quiz = page.locator('.w-quiz'), choices = quiz.locator('.quiz-choices button'), answer = quiz.locator('.quiz-answer');
  assert.equal(await choices.count(), 3);
  assert.equal(await answer.isVisible(), false);
  await page.keyboard.press('ArrowDown');
  assert.equal(await answer.isVisible(), true);
  assert.match(await answer.textContent(), /Answer: Latency 99% of requests beat.*The tail matters/s);
  await quiz.locator('.quiz-reset').click();
  assert.equal(await answer.isVisible(), false);
  await choices.first().focus();
  await page.keyboard.press('Space');
  assert.equal(await page.evaluate(() => Deck.cur), 0, 'Space activates choice without leaving the slide');
  assert.match(await quiz.locator('.quiz-status').textContent(), /Not quite/);
  assert.equal(await choices.first().evaluate(b => document.activeElement === b), true, 'Native quiz activation retains keyboard focus');
  await page.keyboard.press('Space');
  assert.equal(await page.evaluate(() => Deck.cur), 0, 'Repeated activation stays on the question');
  assert.equal(await choices.first().getAttribute('aria-pressed'), 'true');
  await choices.nth(1).focus();
  await page.keyboard.press('Enter');
  assert.equal(await quiz.locator('.quiz-status').textContent(), 'Correct.');
  assert.equal(await quiz.locator('[aria-pressed=true]').count(), 1);
  await page.keyboard.press('s');
  assert.match(await page.locator('#src').textContent(), /::: quiz/);
  assert.match(await page.locator('#src').textContent(), /\[x\]/);
  await page.keyboard.press('Escape');
  await page.evaluate(() => Deck.setView('read'));
  await quiz.locator('.quiz-reset').click();
  assert.equal(await answer.isVisible(), true, 'article answer is readable even after reset');
  assert.equal(await quiz.locator('[aria-pressed=true]').count(), 0);
  assert.equal(await quiz.locator('.quiz-status').textContent(), '');
  assert.match(await page.locator('.td-error').textContent(), /quiz:/);
  assert.match(await page.locator('#stage').textContent(), /Keep this prose/);
  await page.setViewportSize({ width: 320, height: 740 });
  assert.equal(await choices.evaluateAll(bs => bs.every(b => {
    const r = b.getBoundingClientRect();
    return r.height >= 44 && r.x >= 0 && r.right <= innerWidth;
  })), true, 'article choices fit phone and offer 44px touch targets');
  await choices.nth(1).click();
  assert.equal(await quiz.locator('.quiz-status').textContent(), 'Correct.');
  await page.evaluate(() => { Deck.setView('present'); Deck.go(0, 0); });
  assert.equal(await answer.isVisible(), false, 'return to initial slide restores unanswered state');
};
